#feeds into gen
def setup_locations(options: THAWOptions):
    temp_location_table = {}
    temp_location_table.update({**THAW_hollywood_locations})

    if (options.end_goal == options.end_goal.option_smash_the_t_rex):
        temp_location_table.update({**THAW_hollywood_shop_locations})
        temp_location_table.update({**endgoal_t_rex_locations})
    if (options.end_goal == options.end_goal.option_get_to_the_skate_ranch):
        temp_location_table.update({**endgoal_skate_ranch_locations})
        temp_location_table.update({**THAW_beverly_hills_locations})
        temp_location_table.update({**THAW_beverly_hills_shop_locations})
        temp_location_table.update({**THAW_hollywood_shop_locations})
    if options.end_goal == options.end_goal.option_win_the_skate_competition:
        temp_location_table.update({**THAW_beverly_hills_locations})
        temp_location_table.update({**THAW_skateranch_locations})
        temp_location_table.update({**THAW_downtown_locations})
        temp_location_table.update({**THAW_hollywoodstage2_locations})
        temp_location_table.update({**THAW_beverlyhillsstage2_locations})
        temp_location_table.update({**THAW_downtownstage2_locations})
        temp_location_table.update({**THAW_skateranchstage2_locations})
        temp_location_table.update({**THAW_skateranchpiecemissions_locations})
        temp_location_table.update({**THAW_vanspark_locations})
        temp_location_table.update({**endgoal_win_the_skate_competition_locations})
        if options.shopsanity==True:
            temp_location_table.update({**THAW_hollywood_shop_locations})
            temp_location_table.update({**THAW_beverly_hills_shop_locations})
            temp_location_table.update({**THAW_downtown_shop_locations})
    
    return temp_location_table